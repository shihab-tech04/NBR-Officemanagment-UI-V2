CREATE TABLE IF NOT EXISTS demo_payment.story_payments(
  id uuid PRIMARY KEY,
  service_code text NOT NULL,
  amount_minor bigint NOT NULL,
  status text NOT NULL,
  data jsonb NOT NULL
);
